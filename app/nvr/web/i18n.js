export const LANGS = { vi: 'Tiếng Việt', en: 'English' };

function saved() {
  try {
    const v = JSON.parse(localStorage.getItem('camnas.lang'));
    if (v in LANGS) return v;
  } catch { /* chưa lưu hoặc trình duyệt chặn bộ nhớ */ }
  return 'vi';
}

export const lang = saved();
document.documentElement.lang = lang;

export function setLang(value) {
  try { localStorage.setItem('camnas.lang', JSON.stringify(value)); } catch { /* bỏ qua */ }
  location.reload();
}

export function t(text, params) {
  let s = lang === 'en' ? (EN[text] ?? text) : text;
  if (params) s = s.replace(/\{(\w+)\}/g, (m, k) => (params[k] ?? m));
  return s;
}

