"""Chạy go2rtc như tiến trình con.

go2rtc giữ đúng MỘT kết nối tới mỗi camera, rồi chia luồng cho bộ ghi (ffmpeg)
và cho trình duyệt xem trực tiếp. Camera wifi thường giới hạn số kết nối nên
cách này ổn định hơn nhiều so với để mỗi bên tự kết nối thẳng vào camera.
"""
from __future__ import annotations

import asyncio
import json
import time

import httpx

from .config import DATA_DIR, FFMPEG, GO2RTC_API_PORT, GO2RTC_BIN, GO2RTC_RTSP_PORT, GO2RTC_URL, Camera
from .events import EventLog


def stream_names(cam: Camera) -> list[str]:
    return [cam.id, f"{cam.id}_sub"] if cam.sub_url else [cam.id]


def render_config(cameras: list[Camera]) -> str:
    lines = [
        "# Generated by CamNAS - manual edits will be overwritten",
        "api:",
        f'  listen: "127.0.0.1:{GO2RTC_API_PORT}"',
        "rtsp:",
        f'  listen: "127.0.0.1:{GO2RTC_RTSP_PORT}"',
        "ffmpeg:",  # dùng để lấy ảnh chụp (frame.jpeg)
        f"  bin: {json.dumps(FFMPEG)}",
    ]
    if not cameras:
        lines.append("streams: {}")
    else:
        lines.append("streams:")
        for cam in cameras:
            # chuỗi JSON cũng là chuỗi YAML hợp lệ, tránh lỗi với ký tự đặc biệt trong mật khẩu
            lines.append(f"  {cam.id}: {json.dumps(cam.url)}")
            if cam.sub_url:
                lines.append(f"  {cam.id}_sub: {json.dumps(cam.sub_url)}")
    return "\n".join(lines) + "\n"


class Go2rtc:
    def __init__(self, events: EventLog):
        self.events = events
        self.config_path = DATA_DIR / "go2rtc.yaml"
        self.client = httpx.AsyncClient(base_url=GO2RTC_URL, timeout=10)
        self.streams: set[str] = set()
        self._proc: asyncio.subprocess.Process | None = None
        self._task: asyncio.Task | None = None
        self._restarting = False
        self._stopping = False
        self._asset_cache: dict[str, bytes] = {}

    def needs_update(self, cameras: list[Camera]) -> bool:
        try:
            return self.config_path.read_text(encoding="utf-8") != render_config(cameras)
        except FileNotFoundError:
            return True

    def _write(self, cameras: list[Camera]) -> None:
        self.config_path.parent.mkdir(parents=True, exist_ok=True)
        self.config_path.write_text(render_config(cameras), encoding="utf-8")
        self.streams = {name for cam in cameras for name in stream_names(cam)}

    async def start(self, cameras: list[Camera]) -> None:
        self._write(cameras)
        self._task = asyncio.create_task(self._supervise())
        await self.wait_ready()

    async def _supervise(self) -> None:
        backoff = 1
        while not self._stopping:
            try:
                self._proc = await asyncio.create_subprocess_exec(
                    GO2RTC_BIN, "-config", str(self.config_path), stdin=asyncio.subprocess.DEVNULL
                )
            except OSError as e:
                self.events.add("error", "Không chạy được go2rtc ({error}) - xem trực tiếp và ghi hình sẽ không hoạt động", error=str(e))
                return
            started = time.monotonic()
            code = await self._proc.wait()
            if self._stopping:
                return
            if self._restarting:
                self._restarting = False
                backoff = 1
                continue
            if time.monotonic() - started > 60:
                backoff = 1
            self.events.add("warn", "go2rtc dừng bất thường (mã {code}), đang khởi động lại", code=code)
            await asyncio.sleep(backoff)
            backoff = min(backoff * 2, 30)

    async def apply(self, cameras: list[Camera]) -> None:
        """Ghi lại cấu hình và khởi động lại go2rtc nếu danh sách camera thay đổi."""
        if not self.needs_update(cameras):
            return
        self._write(cameras)
        if self._proc and self._proc.returncode is None:
            self._restarting = True
            self._proc.terminate()
            await self._proc.wait()
        await self.wait_ready()

    async def wait_ready(self, timeout: float = 15) -> bool:
        deadline = time.monotonic() + timeout
        while time.monotonic() < deadline and not (self._task and self._task.done()):
            try:
                r = await self.client.get("/api", timeout=2)
                if r.status_code == 200:
                    return True
            except httpx.HTTPError:
                pass
            await asyncio.sleep(0.3)
        return False

    @property
    def running(self) -> bool:
        return self._proc is not None and self._proc.returncode is None

    async def stop(self) -> None:
        self._stopping = True
        if self._proc and self._proc.returncode is None:
            self._proc.terminate()
            try:
                await asyncio.wait_for(self._proc.wait(), 5)
            except asyncio.TimeoutError:
                self._proc.kill()
        if self._task:
            self._task.cancel()
        await self.client.aclose()

    async def snapshot(self, src: str) -> bytes | None:
        try:
            r = await self.client.get("/api/frame.jpeg", params={"src": src}, timeout=15)
        except httpx.HTTPError:
            return None
        return r.content if r.status_code == 200 else None

    async def asset(self, name: str) -> bytes | None:
        """Lấy file JS trình phát của go2rtc (video-rtc.js) để trình duyệt dùng lại."""
        if name not in self._asset_cache:
            try:
                r = await self.client.get(f"/{name}")
            except httpx.HTTPError:
                return None
            if r.status_code != 200:
                return None
            self._asset_cache[name] = r.content
        return self._asset_cache[name]
